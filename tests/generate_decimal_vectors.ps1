# Rebuild the portable decimal arithmetic oracle from .NET's System.Decimal.
$ErrorActionPreference = 'Stop'
$decimalRandom = [Random]::new(20261026)
$decimalCulture = [Globalization.CultureInfo]::InvariantCulture
$decimalRows = [Collections.Generic.List[string]]::new()
$decimalRows.Add('#ifndef __CX_DECIMAL_VECTORS_H__')
$decimalRows.Add('#define __CX_DECIMAL_VECTORS_H__')
$decimalRows.Add('')
$decimalRows.Add('// Generated by generate_decimal_vectors.ps1 using System.Decimal; do not edit.')
$decimalRows.Add('static const struct decimal_vector { const char *left, *right, *result; int operation, error; } decimal_vectors[] = {')
for ($decimalIndex = 0; $decimalIndex -lt 80; ++$decimalIndex) {
    $decimalOperands = foreach ($decimalOperand in 0..1) {
        $decimalWords = foreach ($decimalWord in 0..2) {
            [BitConverter]::ToInt32([BitConverter]::GetBytes([uint32]$decimalRandom.NextInt64(0, 4294967296)), 0)
        }
        [decimal]::new($decimalWords[0], $decimalWords[1], $decimalWords[2],
            [bool]$decimalRandom.Next(2), [byte]$decimalRandom.Next(29))
    }
    for ($decimalOperation = 0; $decimalOperation -lt 5; ++$decimalOperation) {
        $decimalError = 0
        try {
            $decimalResult = switch ($decimalOperation) {
                0 { [decimal]::Add($decimalOperands[0], $decimalOperands[1]) }
                1 { [decimal]::Subtract($decimalOperands[0], $decimalOperands[1]) }
                2 { [decimal]::Multiply($decimalOperands[0], $decimalOperands[1]) }
                3 { [decimal]::Divide($decimalOperands[0], $decimalOperands[1]) }
                4 { [decimal]::Remainder($decimalOperands[0], $decimalOperands[1]) }
            }
        } catch { $decimalError = 1; $decimalResult = [decimal]0 }
        $decimalRows.Add(('    {{ "{0}", "{1}", "{2}", {3}, {4} }},' -f
            $decimalOperands[0].ToString($decimalCulture), $decimalOperands[1].ToString($decimalCulture),
            $decimalResult.ToString($decimalCulture), $decimalOperation, $decimalError))
    }
}
$decimalRows.Add('};')
$decimalRows.Add('')
$decimalRows.Add('#endif // __CX_DECIMAL_VECTORS_H__')
[IO.File]::WriteAllLines((Join-Path $PSScriptRoot 'decimal_vectors.h'), $decimalRows)
